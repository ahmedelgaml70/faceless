#!/usr/bin/env python3
"""Script + REAL licensed Wikimedia Commons photographs only.

No SVGs, drawn diagrams, vector art, generated backgrounds, AI images, or
synthetic stock. If the subject cannot be illustrated with reasonably relevant
rights-compatible photographs, the workflow fails closed before rendering.
"""
from __future__ import annotations

from collections import Counter
from html.parser import HTMLParser
from io import BytesIO
import html
import json
import logging
import os
from pathlib import Path
import re
import sys
import time
from urllib.parse import urlparse

import requests
from PIL import Image, ImageOps, UnidentifiedImageError

from purffle_shorts.config import Settings
from purffle_shorts.llm import LLM
from purffle_shorts.script import write_script, review_script

LOG = logging.getLogger("faceless")
PREPARED = Path("prepared")
MEDIA = Path("media")
COMMONS = "https://commons.wikimedia.org/w/api.php"
HEADERS = {"User-Agent": "FacelessScienceBot/0.5 (https://github.com/ahmedelgaml70/faceless)",
           "Accept": "application/json"}
BAD_TITLE = ("logo", "trademark", "flag of", "icon of", "sounders", "football",
             "soccer", "concert poster", "album cover", "movie poster", "clipart",
             "diagram", "schematic", "drawing", "illustration", "cartoon",
             "rendering", "rendered", "vector", "painting", "screenshot",
             "map of", "ai-generated", "midjourney", "stable diffusion", "dall-e",
             "synthetic image", "meme", "poster", "graphic design", "infographic",
             "artwork", ".svg")
STOP = {"that","from","with","into","near","over","under","this","those",
        "some","there","their","close","photo","stock","image","video",
        "light","bright","dark","high","low","view","scene","visual","sound"}
# Real photography, not generic design stock or speculative composites.
MAX_REUSE = 2
MIN_UNIQUE = 3


class TagStripper(HTMLParser):
    def __init__(self):
        super().__init__()
        self.parts = []

    def handle_data(self, data):
        self.parts.append(data)


def plain(text: str) -> str:
    parser = TagStripper()
    parser.feed(html.unescape(str(text or "")))
    return " ".join(" ".join(parser.parts).split())[:180]


def rights(info: dict) -> tuple[str, str] | None:
    license_name = plain(info.get("LicenseShortName", {}).get("value", ""))
    license_link = str(info.get("LicenseUrl", {}).get("value", ""))
    norm = license_name.casefold().replace(" ","").replace("-","")
    if "cc0" in norm or norm in ("publicdomain","pd","pdold","pduse"):
        return (license_name or "Public domain", license_link)
    if norm in ("ccby2.0","ccby3.0","ccby4.0") and \
            license_link.startswith("https://creativecommons.org/licenses/by/"):
        return license_name, license_link
    return None


def stems(text: str) -> set[str]:
    out = set()
    for word in re.findall(r"[a-z]{3,}", text.casefold()):
        if word in STOP:
            continue
        if word.endswith("ies"):
            word = word[:-3] + "y"
        elif word.endswith("ing") and len(word) > 5:
            word = word[:-3]
        elif word.endswith("es") and len(word) > 5:
            word = word[:-2]
        elif word.endswith("s") and len(word) > 4:
            word = word[:-1]
        out.add(word)
    return out


def candidates(query: str) -> list[dict]:
    params = {"action":"query","generator":"search","gsrsearch":query[:90],
              "gsrnamespace":6,"gsrlimit":24,"prop":"imageinfo",
              "iiprop":"url|size|mime|extmetadata","iiurlwidth":1200,
              "format":"json","formatversion":2}
    reply=requests.get(COMMONS, params=params, headers=HEADERS, timeout=15)
    reply.raise_for_status()
    out=[]
    for item in reply.json().get("query", {}).get("pages", []):
        title=item.get("title","")
        name=title.casefold()
        if any(bad in name for bad in BAD_TITLE):
            continue
        entry=(item.get("imageinfo") or [{}])[0]
        if entry.get("mime") not in ("image/jpeg","image/png","image/webp"):
            continue  # expressly NO SVG (even if its preview is PNG)
        license_info=rights(entry.get("extmetadata") or {})
        if not license_info:
            continue
        info=entry.get("extmetadata") or {}
        artist=plain(info.get("Artist",{}).get("value","")) or "Unknown contributor"
        if "by" in license_info[0].casefold() and artist == "Unknown contributor":
            continue
        description=plain(info.get("ImageDescription",{}).get("value","")).casefold()
        if any(bad in description for bad in ("ai-generated","generated by artificial",
                 "generated with midjourney","generated with stable diffusion")):
            continue
        url=entry.get("thumburl") or entry.get("url") or ""
        parsed=urlparse(url)
        if parsed.scheme!="https" or parsed.hostname != "upload.wikimedia.org":
            continue
        source={"title":title, "page":entry.get("descriptionurl",""),
                "url":url,"artist":artist,"license":license_info[0],
                "license_url":license_info[1],
                "width":entry.get("width",0), "height":entry.get("height",0)}
        out.append(source)
    return out


def get_photo(source: dict) -> Image.Image:
    url=source["url"]
    res=requests.get(url, headers={"User-Agent":HEADERS["User-Agent"],
                                  "Accept":"image/*"}, timeout=24)
    res.raise_for_status()
    if len(res.content)>14_000_000 or not res.headers.get("Content-Type","").startswith("image/"):
        raise ValueError("Invalid/oversized Commons file")
    with Image.open(BytesIO(res.content)) as f:
        if f.width<550 or f.height<360:
            raise ValueError("Stock image too small for vertical video")
        return ImageOps.exif_transpose(f).convert("RGB")


def topic_query(topic: str) -> str:
    # Remove question scaffolding for more useful Wikimedia searches.
    topic=re.sub(r"^(why|how|what|where|when)\s+", "", topic, flags=re.I)
    topic=re.sub(r"\b(does|do|is|are|can|the|a|an|have|has|its|it|that|from|to)\b", " ", topic, flags=re.I)
    return " ".join(topic.split()[:4])


def choose_photo(query: str, topic: str, used: Counter,
                 memo: dict[str,list[dict]]) -> tuple[Image.Image, dict, str]:
    simplified=" ".join(query.split()[:2])
    broad=topic_query(topic)
    searches=list(dict.fromkeys(x for x in (query,simplified,broad,topic) if x))
    for phrase in searches:
        if phrase not in memo:
            try:
                memo[phrase]=candidates(phrase)
            except (requests.RequestException,ValueError) as e:
                LOG.warning("Commons search failed for %r: %s",phrase,str(e)[:140])
                memo[phrase]=[]
        q_words=stems(phrase)
        # Stronger intersection for the primary scene query, otherwise require
        # legitimate overlap with the broader *topic* (real but illustrative B-roll).
        pool=[]
        for item in memo[phrase]:
            overlap=len(q_words & stems(item["title"]))
            required=2 if len(q_words)>=3 else 1
            if overlap<required or used[item["page"]]>=MAX_REUSE:
                continue
            pool.append((overlap,item))
        pool.sort(key=lambda x:(used[x[1]["page"]],-x[0]))
        for overlap,src in pool[:10]:
            try:
                photo=get_photo(src)
            except (requests.RequestException,ValueError,UnidentifiedImageError,OSError) as exc:
                LOG.warning("Commons image rejected %s: %s",src["title"][:70],str(exc)[:90])
                continue
            used[src["page"]]+=1
            src=dict(src, title_overlap_terms=overlap)
            return photo,src,"direct" if phrase in (query,simplified) else "topic-broll"
    raise RuntimeError(f"No licensed REAL photo for scene query {query!r}. "
                       "Refusing a drawn/irrelevant fallback. Try a more filmable topic.")


def full_frame_photo(photo: Image.Image) -> Image.Image:
    """Actual photograph, minimally cropped; no frames, vectors, or labels."""
    return ImageOps.fit(photo,(720,1280),Image.Resampling.LANCZOS,
                        centering=(.5,.45))


def prepare(topic: str) -> None:
    PREPARED.mkdir(exist_ok=True)
    MEDIA.mkdir(exist_ok=True)
    settings=Settings.from_env()
    settings.script_review="rewrite"
    llm=LLM(settings)
    context=(
        "Write a compelling educational SHORT optimized for authentic stock photography. "
        "Only well-established facts, precise units, no dramatic misleading comparisons "
        "or fabricated research. About 6-8 scenes, natural conversational narration, "
        "high-energy specific hook, satisfying final insight. "
        "For EACH scene, search_query must be a concrete 2-4 word REAL-WORLD PHOTOGRAPHY "
        "subject that Wikimedia Commons might contain, such as 'lightning thunderstorm', "
        "'storm clouds', 'cloud to ground lightning'. "
        "NEVER ask for diagrams, animation, vectors, abstract visualization, "
        "impossible microscopic imagery, AI illustrations, or photo-realistic fantasy. "
        "Use grounded search terms repeated from the topic when relevant. "
        "Avoid generic 'subscribe' closers. All visuals must be real photographs."
    )
    script=write_script(llm,topic,settings,style="explainer",context=context)
    script=review_script(llm,script,settings)
    if not 5<=len(script.scenes)<=11:
        raise RuntimeError(f"Invalid scene count: {len(script.scenes)}")
    if script.score is not None and script.score<55:
        raise RuntimeError(f"Script self-review score too low: {script.score}")

    manifest=[]
    used=Counter()
    memo={}
    credits=[]
    for i,scene in enumerate(script.scenes):
        query=scene.search_query.strip()
        photo,source,match=choose_photo(query,topic,used,memo)
        token=f"facelessscene{chr(ord('a')+i)}"
        filename=MEDIA / f"{token}_photo.jpg"
        full_frame_photo(photo).save(filename,quality=91,optimize=True,subsampling=0)
        manifest.append({"index":i,"query":query,"kind":"wikimedia-photo",
                         "match":match,"asset":str(filename),"source":source})
        if "by" in source["license"].casefold():
            credit=f'Photo: {source["artist"]}, {source["title"]}, {source["license"]} ({source["license_url"]}), {source["page"]}'
            if credit not in credits:
                credits.append(credit)
        scene.search_query=token
        print(f"Photo {i+1}/{len(script.scenes)}: {source['title'][:65]} [{match}]",flush=True)
    distinct=len(used)
    if distinct<MIN_UNIQUE:
        raise RuntimeError(f"Only {distinct} unique REAL licensed images; need {MIN_UNIQUE}. "
                           "No diagrams or AI images will be used.")
    if credits:
        script.description += "\n\nPhoto credits:\n"+"\n".join(credits)
    (PREPARED/"script.json").write_text(
        json.dumps(script.to_dict(),indent=2,ensure_ascii=False),encoding="utf-8")
    (PREPARED/"visual_manifest.json").write_text(json.dumps({
        "topic":topic,"visual_policy":"licensed-real-photography-only",
        "unique_photos":distinct,"scenes":manifest
    },indent=2,ensure_ascii=False),encoding="utf-8")
    print(f"PREPARED {len(manifest)} scenes with {distinct} unique REAL licensed photographs",flush=True)


if __name__=="__main__":
    logging.basicConfig(level=logging.INFO)
    subject=" ".join(sys.argv[1:]).strip()
    if not subject:
        raise SystemExit("Provide a video topic")
    prepare(subject)
